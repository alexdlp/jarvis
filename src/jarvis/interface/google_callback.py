"""Receive Google's authorization response."""

import os
import json
import re

import boto3 
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError

from mcp.server import MCPServer
from oauthlib.oauth2 import OAuth2Error
from requests.exceptions import RequestException
from starlette.requests import Request
from starlette.responses import HTMLResponse

from jarvis.integrations.google_oauth import exchange_google_authorization_code
from jarvis.storage.dynamodb import PersistenceError
from jarvis.storage.google_oauth import (
    InvalidGoogleOAuthRequest,
    consume_google_oauth_request,
    save_google_credentials
)


def forward_google_callback(
        request: Request,
        workspace: str,
) -> HTMLResponse:
    """Forwar the callbacks to another deployment"""

    # Only main may forward callback to another deployment.
    if os.environ["JARVIS_WORKSPACE"] != "main":
        return HTMLResponse(
            "This connection cannot be completed here.",
            status_code=409
        )

    # Accept only identifiers complatible with our workspace naming rules
    valid_workspace = re.fullmatch(
        r"[a-z0-9]+(?:-{1,2}[a-z0-9]+)*",
        workspace,
    )
    if not valid_workspace or len(workspace) > 41:
        return HTMLResponse(
            "Invalid authorization state.",
            status_code=400,
        )

    # AWS provides the current function name automatically
    # In main, append the destination workspace to that name
    function_name = (
        f"{os.environ['AWS_LAMBDA_FUNCTION_NAME']}-{workspace}"
    )

    try:
        # Bound the wait and avoid automatically repeating a consumed request.
        client = boto3.client(
            "lambda",
            config = Config(
                connect_timeout = 2,
                read_timeout = 20,
                retries = {"total_max_attempts":1},
            ),
        )

        # Invoke the destination Lambda with the original API Gateway event. 
        response = client.invoke(
            FunctionName = function_name,
            InvocationType = "RequestResponse",
            Payload = json.dumps(request.scope["aws.event"]).encode("utf-8"),
        )

        # Lambda returns its results through a stream containing JSON
        with response["Payload"] as payload:
            result = json.load(payload)

    except (BotoCoreError, ClientError):
        return HTMLResponse(
            "The authorization service could not be reached.",
            status_code=502,
        )

    # A Lambda execution error is different from an HTTP error response.
    if response.get("FunctionError"):
        return HTMLResponse(
            "The authorization service could not complete the request.",
            status_code=502,
        )

    # Preserve the HTML response generated by the destination callback.
    return HTMLResponse(
        content=result["body"],
        status_code=result["statusCode"],
        headers=result.get("headers"),
    )



def register(mcp:MCPServer) -> None:
    """Register the Google authorization callback"""

    @mcp.custom_route("/oauth/google/callback", methods=["GET"])
    async def google_callback(request: Request) -> HTMLResponse:

        # Handle the user rejecting Google's permission request
        if request.query_params.get("error"):
            return HTMLResponse(
                "Google Calendar authorization was not completed.",
                status_code=400
            )

        # Read the values Google returns in the callback URL
        code = request.query_params.get("code")
        state = request.query_params.get("state")

        # Require both values before accessing storage or contacting Google.     
        if not code or not state:
            return HTMLResponse(
                "Missing authorization code os state.",
                status_code=400
            )

        # Separate the originating workspace from the random identifier.
        workspace, separator, nonce = state.partition(".")

        # Require both parts of the authorization identifier.
        if not separator or not nonce:
            return HTMLResponse(
                "Invalid authorization state.",
                status_code=400,
            )

        # Let the originating deployment process its own pending request.
        if workspace != os.environ["JARVIS_WORKSPACE"]:
            return forward_google_callback(request, workspace)

        try: 

            # Retrieve a valid request and prevent it from being used.
            pending = consume_google_oauth_request(state)

            # Exchange Google's code using the original private verifier
            credentials = exchange_google_authorization_code(
                code = code, 
                code_verifier=pending["code_verifier"]
            )

            # Store the connection for the user who initiated the request.
            save_google_credentials(
                user_id=pending["user_id"],
                credentials=credentials
            )

        except InvalidGoogleOAuthRequest:
            # Reject unknown, expired, or already consumed requests. 
            return HTMLResponse(
                "This authorization request is invalid or expired.",
                status_code=400
            )

        except (OAuth2Error, ValueError):

            # Handle a rejected exchange or missing renewable credentials.
            return HTMLResponse(
                "Google authorization failed. Please start again Jarvis.",
                status_code=400
            )

        except (RequestException, PersistenceError):
            # Handle failures contacting Google or accessing storage
            return HTMLResponse(
                "The connection could not be saved. Please try again.",
                status_code=502
            )

        # Return a browser response without exposing tokens or the verifier.
        return HTMLResponse(
            "Google Calendar connected. You can return to ChatGPT.",
            headers={
                "Cache-Control":"no-store",
                "Referrer-Policy":"no-referrer"
            }
        )